#!/usr/bin/env node
// tracks-index.mjs — derive .claude/tracks/index.md from each track's frontmatter and its
// "Resume here" section, so the registry cannot drift from the tracks it lists.
//
//   node .claude/scripts/tracks-index.mjs            # rewrite index.md
//   node .claude/scripts/tracks-index.mjs --check    # exit 1 if index.md is out of date
//   node .claude/scripts/tracks-index.mjs --print    # render to stdout only
//
// A track is `NNN-slug.md` with frontmatter `id/title/status/created/updated/worktree`.
// A sub-document is any other `.md` in the directory carrying `parent: NNN-slug` in its
// frontmatter; it is listed under "Sub-documents", never as its own row. Files with neither
// are left out here and flagged by context-health.mjs.

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'fs';
import { join } from 'path';
import { fileURLToPath } from 'url';

const STATUS_ORDER = ['active', 'blocked', 'paused', 'proposed', 'done', 'abandoned'];
const DEFAULT_NEXT_MAX = 220;

export function parseFrontmatter(content) {
  const m = content.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) return { fm: null, body: content };
  const fm = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*?)\s*$/);
    if (!kv) continue;
    let v = kv[2].replace(/\s+#.*$/, '').trim(); // strip trailing "# comment"
    if (v === 'null' || v === '~' || v === '') v = null;
    fm[kv[1]] = v;
  }
  return { fm, body: m[2] };
}

function section(body, heading) {
  const re = new RegExp(`^##\\s+${heading}\\s*$([\\s\\S]*?)(?=^##\\s|(?![\\s\\S]))`, 'mi');
  const m = body.match(re);
  return m ? m[1] : '';
}

function firstLine(text) {
  for (const raw of text.split('\n')) {
    const l = raw.trim();
    if (!l || /^<!--/.test(l) || /^\|/.test(l) || /^#/.test(l)) continue;
    return l;
  }
  return '';
}

export function nextAction(body, max = DEFAULT_NEXT_MAX) {
  let l = firstLine(section(body, 'Resume here'));
  l = l.replace(/^[-*]\s+/, '').replace(/^\d+\.\s+/, '');
  l = l.replace(/\s+/g, ' ').replace(/\|/g, '\\|');
  if (l.length > max) l = l.slice(0, max - 1).replace(/\s+\S*$/, '') + '…';
  return l || '—';
}

export function loadTracks(repoRoot) {
  const dir = join(repoRoot, '.claude/tracks');
  const tracks = [];
  const subdocs = [];
  const orphans = [];
  for (const f of existsSync(dir) ? readdirSync(dir).sort() : []) {
    if (!f.endsWith('.md') || f === 'README.md' || f === 'index.md') continue;
    const content = readFileSync(join(dir, f), 'utf8');
    const { fm, body } = parseFrontmatter(content);
    if (fm && fm.id) {
      tracks.push({ file: f, fm, body, bytes: Buffer.byteLength(content) });
    } else if (fm && fm.parent) {
      const h1 = body.match(/^#\s+(.+)$/m);
      subdocs.push({ file: f, parent: fm.parent, title: fm.title || (h1 ? h1[1].trim() : f) });
    } else {
      orphans.push(f);
    }
  }
  return { tracks, subdocs, orphans };
}

export function render(repoRoot, opts = {}) {
  const max = opts.nextActionMaxChars || DEFAULT_NEXT_MAX;
  const { tracks, subdocs } = loadTracks(repoRoot);
  const byStatus = new Map();
  for (const t of tracks) {
    const s = (t.fm.status || 'unknown').toLowerCase();
    if (!byStatus.has(s)) byStatus.set(s, []);
    byStatus.get(s).push(t);
  }
  const sortRows = (rows) => rows.sort((a, b) => (b.fm.updated || '').localeCompare(a.fm.updated || '') || b.fm.id.localeCompare(a.fm.id));
  const idCell = (t) => `[${t.fm.id.slice(0, 3)}](${t.file})`;
  const cell = (v) => (v == null ? '—' : String(v).replace(/\|/g, '\\|'));

  const out = [];
  out.push('# Track Registry', '');
  out.push('The control plane — every track, its state, and where to resume. **Start here.**');
  out.push('');
  out.push('Generated by `node .claude/scripts/tracks-index.mjs` from each track\'s frontmatter and the');
  out.push('first line of its **Resume here** section. Do not edit by hand — `context-health.mjs` flags');
  out.push('drift. Regenerate after every `handoff` / `close`.');
  out.push('');

  const group = (title, statuses, cols) => {
    const rows = sortRows(statuses.flatMap((s) => byStatus.get(s) || []));
    out.push(`## ${title}`, '');
    if (!rows.length) { out.push('_none_', ''); return; }
    out.push(`| ${cols.join(' | ')} |`);
    out.push(`|${cols.map(() => '---').join('|')}|`);
    for (const t of rows) {
      const vals = cols.map((c) => {
        switch (c) {
          case 'ID': return idCell(t);
          case 'Track': return cell(t.fm.title);
          case 'Status': return cell(t.fm.status);
          case 'Next action': return nextAction(t.body, max);
          case 'Outcome': return nextAction(t.body, max);
          case 'Worktree': return cell(t.fm.worktree);
          case 'Updated': return cell(t.fm.updated);
          default: return '';
        }
      });
      out.push(`| ${vals.join(' | ')} |`);
    }
    out.push('');
  };

  group('Active', ['active'], ['ID', 'Track', 'Next action', 'Worktree', 'Updated']);
  group('Blocked / paused', ['blocked', 'paused'], ['ID', 'Track', 'Status', 'Next action', 'Updated']);
  group('Proposed', ['proposed'], ['ID', 'Track', 'Next action', 'Updated']);
  group('Done / abandoned', ['done', 'abandoned'], ['ID', 'Track', 'Status', 'Outcome', 'Updated']);

  const unknown = [...byStatus.keys()].filter((s) => !STATUS_ORDER.includes(s));
  if (unknown.length) group('Unknown status — fix frontmatter', unknown, ['ID', 'Track', 'Status', 'Updated']);

  if (subdocs.length) {
    out.push('## Sub-documents', '');
    out.push('Companion files owned by a track (`parent:` in frontmatter). Not tracks themselves.', '');
    for (const s of subdocs.sort((a, b) => a.file.localeCompare(b.file))) {
      out.push(`- [${s.file}](${s.file}) — ${cell(s.title)} · parent [[track:${s.parent}]]`);
    }
    out.push('');
  }
  return out.join('\n');
}

// ---- CLI ----
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { repoRoot: resolveRoot, loadBudgets } = await import('./context-config.mjs');
  const repoRoot = resolveRoot();
  const budgets = loadBudgets(repoRoot);
  const rendered = render(repoRoot, { nextActionMaxChars: budgets.tracks?.nextActionMaxChars });
  const indexPath = join(repoRoot, '.claude/tracks/index.md');
  const args = process.argv.slice(2);
  if (args.includes('--print')) {
    process.stdout.write(rendered);
  } else if (args.includes('--check')) {
    const current = existsSync(indexPath) ? readFileSync(indexPath, 'utf8') : '';
    if (current === rendered) { console.log('tracks index: up to date'); process.exit(0); }
    console.log('tracks index: OUT OF DATE — run: node .claude/scripts/tracks-index.mjs');
    process.exit(1);
  } else {
    writeFileSync(indexPath, rendered);
    const { tracks, subdocs, orphans } = loadTracks(repoRoot);
    console.log(`tracks index: wrote ${tracks.length} tracks, ${subdocs.length} sub-documents${orphans.length ? `; ${orphans.length} file(s) without frontmatter skipped: ${orphans.join(', ')}` : ''}`);
  }
}
