#!/usr/bin/env node
// playbook-index.mjs — generate the navigation index of a playbook from its entries, so the
// index can never drift from the content (track 031 P2). The block lives between
// `<!-- nav:begin -->` / `<!-- nav:end -->` under `## Navigation index`; everything else in
// the playbook is untouched.
//
//   node playbook-index.mjs <agent|all>            # rewrite the block in place
//   node playbook-index.mjs <agent|all> --check    # exit 1 if any block is out of date
//
// Agents read THIS block (plus one cross-layer recall) at task start instead of the whole
// playbook, and open a full entry by heading only when pointed at it.

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'fs';
import { join } from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';
import { parsePlaybook } from './knowledge-curated.mjs';

const BEGIN = '<!-- nav:begin — generated by .claude/scripts/playbook-index.mjs; do not edit by hand -->';
const END = '<!-- nav:end -->';
const INTRO = 'What this playbook knows, by section. **Generated** from the entry headings and their `tags:` lines — read this block, then open an entry by its heading only when it (or a recall hit) points at it.';

export function renderNav(content) {
  const sections = parsePlaybook(content).filter((s) => !/navigation index/i.test(s.heading));
  const lines = [BEGIN];
  for (const s of sections) {
    if (!s.entries.length) { lines.push(`- **${s.heading}** — _none yet_`); continue; }
    lines.push(`- **${s.heading}** (${s.entries.length})`);
    for (const e of s.entries) {
      const ents = (e.tags.entities || []).join(', ');
      const track = (e.tags.track || []).map((t) => `track ${t}`).join(', ');
      const meta = [ents, track].filter(Boolean).join(' · ');
      lines.push(`  - ${e.date} · ${e.title}${meta ? ` — ${meta}` : ''}`);
    }
  }
  lines.push(END);
  return lines.join('\n');
}

export function applyNav(content) {
  const block = renderNav(content);
  const re = /^##\s+Navigation index\s*$([\s\S]*?)(?=^##\s|(?![\s\S]))/m;
  const m = content.match(re);
  const section = `## Navigation index\n\n${INTRO}\n\n${block}\n\n`;
  if (!m) {
    // no index section: insert one after the header paragraph (before the first ##)
    const i = content.search(/^##\s/m);
    return i === -1 ? content.trimEnd() + '\n\n' + section : content.slice(0, i) + section + content.slice(i);
  }
  return content.slice(0, m.index) + section + content.slice(m.index + m[0].length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const repoRoot = execSync('git rev-parse --show-toplevel', { encoding: 'utf8' }).trim();
  const dir = join(repoRoot, '.claude/knowledge');
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const target = args.find((a) => !a.startsWith('--'));
  if (!target) { console.error('usage: playbook-index.mjs <agent|all> [--check]'); process.exit(2); }
  const agents = target === 'all'
    ? readdirSync(dir).filter((f) => f.endsWith('.md') && f !== 'README.md').map((f) => f.replace(/\.md$/, ''))
    : [target];
  let stale = 0;
  for (const a of agents) {
    const p = join(dir, `${a}.md`);
    if (!existsSync(p)) { console.error(`no playbook: ${p}`); process.exit(2); }
    const content = readFileSync(p, 'utf8');
    const next = applyNav(content);
    if (next === content) { console.log(`${a}: index up to date`); continue; }
    if (check) { console.log(`${a}: index OUT OF DATE — run: node .claude/scripts/playbook-index.mjs ${a}`); stale++; continue; }
    writeFileSync(p, next);
    console.log(`${a}: index regenerated`);
  }
  process.exit(stale ? 1 : 0);
}
